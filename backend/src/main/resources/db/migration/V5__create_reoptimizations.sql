-- The assets the optimization chose from, so a reoptimization can choose from the same ones.
-- Null for portfolios saved before this column existed: their holdings are used instead.
alter table portfolios add column symbols_json jsonb;

-- How often the portfolio is reoptimized on its own; null when it is not
alter table portfolios add column reoptimization_schedule varchar(20)
    constraint ck_portfolios_reoptimization_schedule check (reoptimization_schedule in ('WEEKLY', 'MONTHLY'));

-- Each run of a portfolio's strategy on newer prices, and how far the portfolio is from its new weights
create table reoptimizations
(
    id              bigint generated by default as identity primary key,
    portfolio_id    bigint                   not null references portfolios (id) on delete cascade,
    status          varchar(20)              not null,
    error           varchar(1000),

    expected_return double precision,
    volatility      double precision,
    sharpe_ratio    double precision,
    statistics_from date,
    statistics_to   date,
    -- Share of the portfolio's value that would change hands to reach the new weights
    turnover        double precision,
    -- [{symbol, currentWeight, targetWeight}]
    changes_json    jsonb,

    created_at      timestamp with time zone not null,

    constraint ck_reoptimizations_status check (status in ('SUCCEEDED', 'FAILED')),
    constraint ck_reoptimizations_result check (status <> 'SUCCEEDED' or (turnover is not null and changes_json is not null)),
    constraint ck_reoptimizations_error check (status <> 'FAILED' or error is not null)
);

create index ix_reoptimizations_portfolio on reoptimizations (portfolio_id, created_at desc);
