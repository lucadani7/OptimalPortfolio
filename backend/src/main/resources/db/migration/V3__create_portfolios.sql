-- Saved allocations. The metrics are a snapshot taken when the portfolio was created.
create table portfolios (
    id               bigint generated by default as identity primary key,
    name             varchar(255)     not null,
    strategy         varchar(64)      not null,
    budget           numeric(19, 2)   not null,
    invested         numeric(19, 2)   not null,
    leftover         numeric(19, 2)   not null,

    expected_return  double precision not null,
    volatility       double precision not null,
    sharpe_ratio     double precision not null,
    risk_free_rate   double precision not null,
    statistics_from  date             not null,
    statistics_to    date             not null,

    -- Constraints exactly as requested, so the optimization can be reproduced
    constraints_json jsonb            not null,

    version          bigint           not null default 0,
    created_at       timestamptz      not null default now(),
    updated_at       timestamptz      not null default now(),

    constraint ck_portfolios_budget   check (budget > 0),
    constraint ck_portfolios_invested check (invested >= 0 and invested <= budget),
    constraint ck_portfolios_leftover check (leftover >= 0)
);

-- Whole shares bought for a portfolio. An asset that is held cannot be deleted.
create table holdings (
    id             bigint generated by default as identity primary key,
    portfolio_id   bigint           not null references portfolios (id) on delete cascade,
    asset_id       bigint           not null references assets (id),
    shares         integer          not null,
    purchase_price numeric(19, 6)   not null,
    price_date     date             not null,
    target_weight  double precision not null,

    constraint uk_holdings_portfolio_asset unique (portfolio_id, asset_id),
    constraint ck_holdings_shares          check (shares > 0),
    constraint ck_holdings_purchase_price  check (purchase_price > 0),
    constraint ck_holdings_target_weight   check (target_weight between 0 and 1)
);

create index ix_holdings_asset on holdings (asset_id);
