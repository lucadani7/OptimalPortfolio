-- Single-table inheritance: every asset kind lives in this table,
-- distinguished by asset_type. Kind-specific columns are nullable.
create table assets (
                        id             bigint generated by default as identity primary key,
                        asset_type     varchar(16)  not null,
                        symbol         varchar(16)  not null,
                        name           varchar(255) not null,
                        sector         varchar(64)  not null,
                        currency       varchar(3)   not null,

    -- STOCK
                        exchange       varchar(32),

    -- ETF
                        expense_ratio  numeric(6, 5),

    -- BOND
                        coupon_rate    numeric(7, 5),
                        maturity_date  date,

                        version        bigint       not null default 0,
                        created_at     timestamptz  not null default now(),
                        updated_at     timestamptz  not null default now(),

                        constraint uk_assets_symbol         unique (symbol),
                        constraint ck_assets_type           check (asset_type in ('STOCK', 'ETF', 'BOND')),
                        constraint ck_assets_symbol_upper   check (symbol = upper(symbol)),
                        constraint ck_assets_currency       check (currency ~ '^[A-Z]{3}$'),
                        constraint ck_assets_expense_ratio  check (expense_ratio is null or expense_ratio between 0 and 1),
                        constraint ck_assets_coupon_rate    check (coupon_rate is null or coupon_rate between 0 and 1),
                        constraint ck_assets_bond_maturity  check (asset_type <> 'BOND' or maturity_date is not null)
);

create index ix_assets_type   on assets (asset_type);
create index ix_assets_sector on assets (sector);