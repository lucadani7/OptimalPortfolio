-- Daily closing prices. Deleting an asset deletes its price history.
create table price_points (
                              id          bigint generated by default as identity primary key,
                              asset_id    bigint         not null references assets (id) on delete cascade,
                              trade_date  date           not null,
                              close       numeric(19, 6) not null,

                              constraint uk_price_points_asset_date unique (asset_id, trade_date),
                              constraint ck_price_points_close      check (close > 0)
);